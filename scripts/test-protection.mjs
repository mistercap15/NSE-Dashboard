import assert from 'node:assert/strict';
import {recommendTarget,buildProtection,payoff,quoteState} from '../app/lib/protection.mjs';
const now=Date.parse('2026-10-19T09:00:00Z');
const p={entry:1000,qty:100,costs:100,capital:2000000,expiryDate:'2026-10-27'};
const o={instrumentKey:'p',lotSize:100,strike:950,expiryDate:p.expiryDate};
const quote={timestamp:now,depth:{buy:[{price:19}],sell:[{price:20,quantity:100}]}};
const run=(options=[o],q=quote)=>buildProtection({position:p,options,quotes:{p:q},target:{price:1100},now});
const r=run();assert.equal(r.choices.length,1);assert.equal(r.choices[0].maxLoss,7100);
for(const s of [0,100,800,950]) assert.equal(payoff(s,p,r.choices[0]),-7100);
assert.equal(r.choices[0].reward,7900);assert.equal(payoff(1100,p),9900);
assert.equal(run([{...o,expiryDate:'2026-11-24'}]).choices.length,0);
assert.equal(run([{...o,lotSize:75}]).choices.length,0);
assert.equal(run([o],{...quote,timestamp:now-121000}).choices.length,0);
assert.equal(run([o],{...quote,depth:{buy:[{price:19}],sell:[{price:20,quantity:99}]}}).choices.length,0);
assert.equal(run([o],{...quote,depth:{buy:[{price:21}],sell:[{price:20,quantity:100}]}}).choices.length,0);
assert.equal(quoteState({}).fresh,false);
const points=Array.from({length:8},(_,i)=>({year:2018+i,month:10,ym:`${2018+i}-10`,ret:6}));
const candles=Array.from({length:70},(_,i)=>({date:new Date(Date.parse('2026-10-17')-i*86400000).toISOString().slice(0,10),close:100,high:110}));
const args={points,candles,spot:100,expiryDate:p.expiryDate,today:'2026-10-18'};
const target=recommendTarget(args);assert.equal(target.price,101.8);assert.equal(target.samples,8);
assert.equal(recommendTarget({...args,points:[...points,{year:2026,month:10,ym:'2026-10',ret:900}]}).price,target.price);
assert.equal(recommendTarget({...args,candles:[...candles,{date:'2026-10-18',high:1000,close:999}]}).price,target.price);
assert.equal(recommendTarget({...args,expiryDate:'2026-11-24'}).price,null);
assert.equal(recommendTarget({...args,points:[]}).price,null);
assert.equal(recommendTarget({...args,today:'2026-10-27'}).price,null);
console.log('Protection: payoff, whole lots, expiry, stale/depth/crossed quotes, causal target and missing-data checks passed.');
const {resolveEntry}=await import('../app/lib/protection.mjs');
assert.equal(resolveEntry({source:'existing',originalEntry:1900,quote:{last_price:2000},qty:100,now}).price,1900);
assert.equal(resolveEntry({source:'market',quote:{...quote,last_price:18},qty:100,now}).price,20);
assert.equal(resolveEntry({source:'market',quote:{timestamp:now,last_price:18},qty:100,now}).price,18);
assert.ok(resolveEntry({source:'market',quote:{timestamp:now,last_price:18},qty:100,now}).issues.some(x=>x.includes('Last')||x.includes('last trade')));
assert.equal(resolveEntry({source:'market',quote:{},qty:100,now}).price,null);
assert.ok(resolveEntry({source:'market',quote,qty:200,now}).issues.some(x=>x.includes('depth')));
console.log('Entry-source checks passed: actual fill preserved, ask preferred, LTP indicative, missing data and insufficient depth flagged.');
