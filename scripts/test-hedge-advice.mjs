import assert from 'node:assert/strict';
import {hedgeAdvice} from '../app/lib/hedgeAdvice.mjs';
const today='2026-10-18',expiryDate='2026-10-27';
const candles=Array.from({length:60},(_,i)=>({date:new Date(Date.parse('2026-08-18')+i*86400000).toISOString().slice(0,10),open:100,high:102,low:98,close:100,volume:1000}));
const args={candles,market:candles,today,expiryDate};
assert.equal(hedgeAdvice(args).status,'Prepare protection');
const broken=[...candles.slice(0,-1),{...candles.at(-1),open:97,high:98,low:94,close:95,volume:2000}];
assert.equal(hedgeAdvice({...args,candles:broken}).status,'Protection warranted');
assert.equal(hedgeAdvice({...args,candles:[...candles,{date:today,open:50,high:60,low:40,close:45,volume:99999}]}).status,'Prepare protection');
assert.equal(hedgeAdvice({...args,candles:[]}).status,'Insufficient data');
assert.equal(hedgeAdvice({...args,today:'2026-11-01'}).status,'Insufficient data');
assert.equal(hedgeAdvice({...args,market:[]}).missing.some(s=>s.includes('NIFTY')),true);
assert.equal(hedgeAdvice(args).exit.includes('Maintain'),true);
const futures=[{date:'2026-10-15',timestamp:'2026-10-15T15:15:00+05:30',close:100,openInterest:1000},{date:'2026-10-16',timestamp:'2026-10-16T15:15:00+05:30',close:95,openInterest:1100}];
assert.ok(Math.abs(hedgeAdvice({...args,futures}).oiChange-10)<1e-8);
assert.equal(hedgeAdvice({...args,futures:[futures[1]]}).oiChange,null);
assert.equal(hedgeAdvice({...args,expiryDate:'2026-10-20'}).exit.includes('Expiry'),true);
console.log('Hedge advice: causal, stale/missing data, OI comparability and expiry tests passed');
const recovery=[...candles.slice(0,-1),{...candles.at(-1),open:101,high:105,low:99,close:104}];
const risingFutures=[futures[0],{...futures[1],close:104,openInterest:1000}];
assert.equal(hedgeAdvice({...args,candles:recovery,futures:risingFutures}).exit.includes('Recovery condition met'),true);
assert.equal(hedgeAdvice({...args,candles:recovery,futures:[]}).exit.includes('Maintain'),true);
